export function isLegacyGeneratedPosterUrl(url?: string): boolean {
  return Boolean(url && /^\/src\/assets\/images\/poster_/i.test(url.trim()));
}

export function findCatalogMatchForMovie(movie: {
  movie_id?: string;
  external_source?: string;
  external_id?: string;
  title?: string;
  original_title?: string;
  release_year?: number;
}): CatalogFilm | undefined {
  if (movie.external_source === 'tmdb' && movie.external_id?.trim()) {
    const byExt = CURATED_CATALOG.find(
      (c) => c.external_id === movie.external_id?.trim()
    );
    if (byExt) return byExt;
  }
  if (movie.movie_id?.startsWith('mov-')) {
    const suffix = movie.movie_id.slice(4);
    const bySlug = CURATED_CATALOG.find((c) => c.catalog_id === `cat-${suffix}`);
    if (bySlug) return bySlug;
  }
  const titleLower = movie.title?.trim().toLowerCase() || '';
  const origLower = movie.original_title?.trim().toLowerCase() || '';
  if (!titleLower && !origLower) return undefined;

  return CURATED_CATALOG.find((c) => {
    const yearClose =
      !movie.release_year || Math.abs(c.release_year - movie.release_year) <= 1;
    if (!yearClose) return false;
    const cTitle = c.title.trim().toLowerCase();
    const cOrig = c.original_title.trim().toLowerCase();
    return (
      (titleLower && (cTitle === titleLower || cOrig === titleLower)) ||
      (origLower && (cOrig === origLower || cTitle === origLower))
    );
  });
}

